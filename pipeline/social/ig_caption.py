def _llm_available() -> bool:
    """True if Gemini flash-lite is usable. Claude is never used for captions
    (retired 2026-06-22); flash-lite is the sole provider."""
    return gemini_client is not None and gemini_client.is_available()


def _generate_caption_json(prompt: str) -> dict | None:
    """Generate one caption via Gemini flash-lite - the sole caption provider.
    Claude is never used (retired 2026-06-22). flash-lite keeps captions off the
    flash 20/day budget the main pipeline's brief + top-10 already spend."""
    if gemini_client is None or not gemini_client.is_available():
        return None
    return gemini_client.generate_json(
        prompt=prompt,
        system_instruction=SYSTEM_PROMPT,
        max_retries=0,  # we handle retries ourselves so we can adjust prompt
        count_call=True,
        max_output_tokens=2048,
        model=gemini_client._MODEL,  # flash-lite - never flash, never Claude
    )


def caption_for_post(row: dict[str, Any], max_retries: int = 3) -> tuple[dict | None, str | None]:
    """Generate the IG caption + X/Bluesky variants + intent from one call.

    Returns (result, error). On success `error` is None and `result` is a dict:
        {caption, hashtags, caption_x, caption_bluesky, intent}
    Only the IG caption + hashtags gate the retry loop; the variants + intent
    are sanitized / derived from the clean caption and never fail the row."""
    if not _llm_available():
        return None, "no caption LLM available (set GEMINI_API_KEY)"

    prompt = _build_user_prompt(row)

    last_err = "unknown"
    for attempt in range(max_retries):
        result = _generate_caption_json(prompt)
        if not result:
            last_err = "LLM returned no JSON"
            continue

        caption_raw = (result.get("caption") or "").strip()
        hashtags_raw = result.get("hashtags") or []
        if isinstance(hashtags_raw, str):
            hashtags_raw = [h.strip() for h in re.split(r"[,\s]+", hashtags_raw) if h.strip()]
        hashtags = [h.lstrip("#").strip() for h in hashtags_raw if isinstance(h, str)]

        ok, msg = _validate(caption_raw, hashtags)
        if ok:
            return {
                "caption": caption_raw,
                "hashtags": hashtags,
                "caption_x": _finalize_variant(result.get("caption_x"), caption_raw, X_MAX_CHARS),
                "caption_bluesky": _finalize_variant(
                    result.get("caption_bluesky"), caption_raw, BLUESKY_MAX_CHARS
                ),
                "intent": _finalize_intent(result.get("intent")),
            }, None

        last_err = msg
        # Tighten prompt for next try
        prompt = (
            _build_user_prompt(row)
            + f"\n\nPREVIOUS ATTEMPT FAILED: {msg}. Fix it. Return STRICT JSON only."
        )

    return None, last_err


def _set_state(post_id: str, state: str, error: str | None = None) -> None:
    payload: dict[str, Any] = {"state": state}
    if error is not None:
        payload["error"] = error[:1000]
    try:
        supabase.table("ig_posts").update(payload).eq("id", post_id).execute()
    except Exception as e:
        print(f"  [error] state update {post_id} → {state}: {e}")


def _write_caption(post_id: str, result: dict) -> None:
    payload = {
        "caption": result["caption"],
        "hashtags": result["hashtags"],
        "caption_x": result.get("caption_x"),
        "caption_bluesky": result.get("caption_bluesky"),
        "intent": result.get("intent"),
    }
    try:
        supabase.table("ig_posts").update(payload).eq("id", post_id).execute()
    except Exception as e:
        # Migration 074 may not be applied yet; retry with the legacy columns
        # only so the caption still lands and the row is not lost.
        msg = str(e).lower()
        if "caption_x" in msg or "caption_bluesky" in msg or "intent" in msg or "column" in msg:
            print(f"  [warn] caption variant columns missing (apply migration 074): {e}")
            try:
                supabase.table("ig_posts").update({
                    "caption": result["caption"],
                    "hashtags": result["hashtags"],
                }).eq("id", post_id).execute()
                return
            except Exception as e2:
                print(f"  [error] caption write {post_id} (legacy fallback): {e2}")
                return
        print(f"  [error] caption write {post_id}: {e}")


def _fetch_targets(post_id: str | None) -> list[dict]:
    q = supabase.table("ig_posts").select("id, slide_specs, pillar, caption, state")
    if post_id:
        q = q.eq("id", post_id)
    else:
        # Caption rows that have rendered images but no caption yet.
        q = q.in_("state", ["draft"]).is_("caption", "null")
    return (q.order("scheduled_for", desc=False).limit(50).execute().data) or []


def caption_all(post_id: str | None = None) -> int:
    rows = _fetch_targets(post_id)
    if not rows:
        print("  [caption] nothing to do")
        return 0

    done = 0
    for row in rows:
        pid = row["id"]
        _set_state(pid, "captioning")
        result, err = caption_for_post(row)
        if result:
            _write_caption(pid, result)
            # leave state at 'draft' so the admin picks it up; the captioning
            # state is a transient lock so concurrent runs don't collide
            _set_state(pid, "draft")
            print(
                f"  [caption] {pid} ok ({len(result['caption'])} chars, "
                f"{len(result['hashtags'])} tags, x={len(result['caption_x'])}c, "
                f"bsky={len(result['caption_bluesky'])}c)"
            )
            done += 1
        else:
            _set_state(pid, "caption_review", err or "validation failed")
            print(f"  [caption] {pid} → caption_review: {err}")
    return done


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--post-id", default=None, help="caption a single post")
    args = parser.parse_args()
    n = caption_all(post_id=args.post_id)
    print(f"  [caption] done. {n} caption(s) written.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
