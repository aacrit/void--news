"""
ig_caption.py - Instagram caption generator (+ per-platform variants + intent).

Captions are generated by Gemini flash-lite, the sole caption provider. Claude
was retired 2026-06-22 and is never used here. System prompt enforces project
voice rules: show-don't-tell, arrive-late-leave-early, no em dashes,
niche-first hashtag stack, 50-130 words, single CTA. Post-process regex checks
bounce captions that violate the rules; up to 3 retries before marking the row
state='caption_review' for manual edit.

The SAME single Gemini call now also returns three extra fields (2026-08-05,
manual-upload pivot; migration 074):
  caption_x        X/Twitter variant, <= 280 chars, at most 1-2 hashtags
  caption_bluesky  Bluesky variant, <= 300 chars, plain (no hashtag wall)
  intent           one-sentence director's note (the emotion/message the post
                   is going for), a cue for the CEO's personal touch at upload.
No extra API call: the variants + intent ride inside the existing JSON output.
Every variant is passed through the same voice rules (no em/en dashes, banned
phrases). If the model omits a variant, X/Bluesky are DERIVED by trimming the
IG caption and intent falls back to a neutral note, rather than failing the row.
ig_export.py reads all of these into the downloadable manual-upload bundle.

Usage:
    python -m pipeline.social.ig_caption                       # all draft captionable
    python -m pipeline.social.ig_caption --post-id <uuid>      # one row

Environment:
    GEMINI_API_KEY      required for caption generation (flash-lite)
    SUPABASE_URL / KEY  existing pipeline vars
"""

